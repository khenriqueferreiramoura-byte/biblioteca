USE BIBLIOTECA_INTELIGENTE;
SET @has_status=(SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='EMPRESTIMO' AND COLUMN_NAME='STATUS');
SET @sql_status=IF(@has_status=0,"ALTER TABLE EMPRESTIMO ADD COLUMN STATUS VARCHAR(15) NOT NULL DEFAULT 'Emprestado'","SELECT 'STATUS já existe' AS aviso");
PREPARE s FROM @sql_status; EXECUTE s; DEALLOCATE PREPARE s;
SET @has_data=(SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='EMPRESTIMO' AND COLUMN_NAME='DATA_DEVOLUCAO');
SET @sql_data=IF(@has_data=0,"ALTER TABLE EMPRESTIMO ADD COLUMN DATA_DEVOLUCAO DATE NULL","SELECT 'DATA_DEVOLUCAO já existe' AS aviso");
PREPARE d FROM @sql_data; EXECUTE d; DEALLOCATE PREPARE d;
DESCRIBE EMPRESTIMO;
